"""Download undersea internet cables from TeleGeography's Submarine Cable Map and pack them into
wallpaper/lib/cables.js (bundled into the wallpaper at build time — the site sends no CORS headers,
so the wallpaper can't fetch it live).

Data © TeleGeography, www.submarinecablemap.com — CC BY-NC-SA 3.0 (fine for a personal, non-commercial gift).
Re-run now and then to pick up new cables:  python3 scripts/fetch_cables.py
"""
import concurrent.futures as cf, json, math, pathlib, time, urllib.request

API = 'https://www.submarinecablemap.com/api/v3/'
UA = {'User-Agent': 'Mozilla/5.0 (deskmate wallpaper build script)'}
OUT = pathlib.Path(__file__).resolve().parent.parent / 'wallpaper' / 'lib' / 'cables.js'


def get(path, tries=4):
    for i in range(tries):
        try:
            with urllib.request.urlopen(urllib.request.Request(API + path, headers=UA), timeout=30) as r:
                return json.load(r)
        except Exception:
            if i == tries - 1:
                raise
            time.sleep(1.5 * (i + 1))


def simplify(line, tol=0.08):
    """Drop points closer than `tol` degrees to the last kept one; round to 2 decimals. Output [lat, lng]."""
    out = []
    for lng, lat in line:
        if out and math.hypot(lat - out[-1][0], lng - out[-1][1]) < tol:
            continue
        out.append([round(lat, 2), round(lng, 2)])
    last = [round(line[-1][1], 2), round(line[-1][0], 2)]
    if out[-1] != last:
        out.append(last)
    return out


geo = get('cable/cable-geo.json')['features']
ids = sorted({f['properties']['id'] for f in geo})
print(len(geo), 'route pieces,', len(ids), 'cables — fetching details…')


def detail(cid):
    try:
        return cid, get(f'cable/{cid}.json')
    except Exception:
        return cid, {}


info = {}
with cf.ThreadPoolExecutor(4) as pool:   # be polite: 4 at a time
    for n, (cid, d) in enumerate(pool.map(detail, ids), 1):
        info[cid] = d
        if n % 100 == 0:
            print(' ', n)

cables, byid = [], {}
for f in geo:
    p = f['properties']
    cid = p['id']
    if cid not in byid:
        d = info.get(cid, {})
        countries = sorted({lp.get('country') for lp in d.get('landing_points') or [] if lp.get('country')})
        owners = (d.get('owners') or '').strip()
        byid[cid] = {
            'n': p['name'], 'c': p.get('color') or '#5ef2ff',
            'len': d.get('length') or '', 'y': d.get('rfs_year') or None, 'planned': bool(d.get('is_planned')),
            'lp': len(d.get('landing_points') or []), 'cc': countries,
            'o': owners if len(owners) <= 90 else owners[:88].rsplit(',', 1)[0] + ', …',
            'paths': [],
        }
        cables.append(byid[cid])
    for line in f['geometry']['coordinates']:
        if len(line) >= 2:
            byid[cid]['paths'].append(simplify(line))

js = ('// Undersea internet cables. Data © TeleGeography (www.submarinecablemap.com), CC BY-NC-SA 3.0.\n'
      '// Generated by scripts/fetch_cables.py on ' + time.strftime('%Y-%m-%d') + ' — do not edit by hand.\n'
      '// n=name c=colour len=length y=ready-for-service year planned lp=#landing points cc=countries o=owners paths=[[lat,lng],…]\n'
      'window.CABLES = ' + json.dumps(cables, ensure_ascii=False, separators=(',', ':')) + ';\n')
OUT.write_text(js)
print(f'{len(cables)} cables, {sum(len(p) for c in cables for p in c["paths"])} points → {OUT} ({len(js)//1024} KB)')
